#!/usr/bin/env node
// Generates src/generated/client.ts from openapi.json.
//
// Not a general purpose OpenAPI generator. It understands exactly the subset this schema
// uses: string enums, flat objects of scalars and $refs, path parameters, a JSON request
// body, and a single success response that is either a $ref or an array of one. Anything
// outside that subset throws rather than emitting something plausible and wrong.
//
// Output is deterministic. Schemas, properties and operations are emitted in sorted order
// so that regenerating without a schema change produces a byte identical file, which is
// what makes drift detectable in CI.
//
// Usage:
//   node tools/generate-client.mjs [outputPath]
//
// outputPath defaults to src/generated/client.ts.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const SCHEMA_PATH = "openapi.json";
const DEFAULT_OUTPUT = "src/generated/client.ts";
const SCALARS = { string: "string", integer: "number", number: "number", boolean: "boolean" };

function refName(ref) {
  const prefix = "#/components/schemas/";
  if (!ref.startsWith(prefix)) {
    throw new Error(`only local schema refs are supported, got ${ref}`);
  }
  return ref.slice(prefix.length);
}

function typeOf(schema, where) {
  if (schema.$ref) {
    return refName(schema.$ref);
  }
  if (schema.type === "array") {
    if (!schema.items) {
      throw new Error(`${where} is an array with no items`);
    }
    return `${typeOf(schema.items, `${where}[]`)}[]`;
  }
  const scalar = SCALARS[schema.type];
  if (!scalar) {
    throw new Error(`${where} has unsupported type ${JSON.stringify(schema.type)}`);
  }
  return scalar;
}

function renderSchema(name, schema) {
  if (schema.enum) {
    const members = [...schema.enum].sort().map((value) => JSON.stringify(value));
    return `export type ${name} = ${members.join(" | ")};\n`;
  }
  if (schema.type !== "object") {
    throw new Error(`schema ${name} is neither an enum nor an object`);
  }
  const required = new Set(schema.required ?? []);
  const lines = [`export type ${name} = {`];
  for (const property of Object.keys(schema.properties ?? {}).sort()) {
    const optional = required.has(property) ? "" : "?";
    lines.push(`  ${property}${optional}: ${typeOf(schema.properties[property], `${name}.${property}`)};`);
  }
  lines.push("};\n");
  return lines.join("\n");
}

function successResponse(operation, operationId) {
  const codes = Object.keys(operation.responses ?? {})
    .filter((code) => code.startsWith("2"))
    .sort();
  if (codes.length !== 1) {
    throw new Error(`${operationId} must declare exactly one 2xx response`);
  }
  const schema = operation.responses[codes[0]]?.content?.["application/json"]?.schema;
  if (!schema) {
    throw new Error(`${operationId} has no application/json success schema`);
  }
  return typeOf(schema, `${operationId} response`);
}

function collectOperations(paths) {
  const operations = [];
  for (const path of Object.keys(paths).sort()) {
    for (const method of Object.keys(paths[path]).sort()) {
      const operation = paths[path][method];
      const operationId = operation.operationId;
      if (!operationId) {
        throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
      }
      const parameters = (operation.parameters ?? [])
        .filter((parameter) => parameter.in === "path")
        .map((parameter) => ({ name: parameter.name, type: typeOf(parameter.schema, parameter.name) }));
      const bodySchema = operation.requestBody?.content?.["application/json"]?.schema;
      operations.push({
        operationId,
        method: method.toUpperCase(),
        path,
        parameters,
        bodyType: bodySchema ? typeOf(bodySchema, `${operationId} body`) : null,
        returnType: successResponse(operation, operationId),
      });
    }
  }
  return operations.sort((a, b) => (a.operationId < b.operationId ? -1 : 1));
}

function signature(operation) {
  const args = operation.parameters.map((parameter) => `${parameter.name}: ${parameter.type}`);
  if (operation.bodyType) {
    args.push(`body: ${operation.bodyType}`);
  }
  return `${operation.operationId}(${args.join(", ")}): Promise<${operation.returnType}>`;
}

function template(operation) {
  return operation.path.replace(/\{([^}]+)\}/g, (_match, name) => `\${${name}}`);
}

function render(schema) {
  const out = [];
  out.push("// Code generated by tools/generate-client.mjs from openapi.json.");
  out.push("// DO NOT EDIT BY HAND. Run `node tools/generate-client.mjs` instead.");
  out.push(`// Schema version: ${schema.info.version}`);
  out.push("");
  out.push("export interface RequestSpec {");
  out.push("  method: string;");
  out.push("  path: string;");
  out.push("  body?: unknown;");
  out.push("}");
  out.push("");
  out.push("export interface Transport {");
  out.push("  request(spec: RequestSpec): Promise<unknown>;");
  out.push("}");
  out.push("");

  const schemas = schema.components?.schemas ?? {};
  for (const name of Object.keys(schemas).sort()) {
    out.push(renderSchema(name, schemas[name]));
  }

  const operations = collectOperations(schema.paths ?? {});
  out.push("export interface ApiClient {");
  for (const operation of operations) {
    out.push(`  ${signature(operation)};`);
  }
  out.push("}");
  out.push("");
  out.push("export function createClient(transport: Transport): ApiClient {");
  out.push("  return {");
  for (const operation of operations) {
    const spec = [`method: "${operation.method}"`, `path: \`${template(operation)}\``];
    if (operation.bodyType) {
      spec.push("body");
    }
    out.push(`    async ${signature(operation)} {`);
    out.push(`      const payload = await transport.request({ ${spec.join(", ")} });`);
    out.push(`      return payload as ${operation.returnType};`);
    out.push("    },");
  }
  out.push("  };");
  out.push("}");
  return `${out.join("\n")}\n`;
}

const output = process.argv[2] ?? DEFAULT_OUTPUT;
const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, render(schema), "utf8");
process.stdout.write(`wrote ${output} from ${SCHEMA_PATH} (schema version ${schema.info.version})\n`);
