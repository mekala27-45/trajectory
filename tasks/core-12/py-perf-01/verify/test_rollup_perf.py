"""Hidden verification suite for py-perf-01.

Half of these check that the rollup is fast and half check that it is still the same
rollup, because the cheap ways to make a timer happy all break something else.

Returning a cached answer for the fixture that ships with the task is ruled out twice:
once by timing a second ledger with a different shape that is generated here, and once by
editing a row of the real fixture and demanding the summary move with it. Losing the
documented key order is ruled out by asserting it on a ledger whose first seen order is
not its sorted order. Mutating or consuming the caller's rows is ruled out by rolling the
same list up twice and comparing the input before and after. Getting refunds wrong is
ruled out by an account that never received a payment, only refunds.
"""

import functools
import random
import sys
import time
from pathlib import Path

WORKSPACE = Path.cwd()
sys.path.insert(0, str(WORKSPACE / "src"))

from rollup import Row, load_rows, summarise  # noqa: E402

FIXTURE = WORKSPACE / "data" / "ledger.csv"
BUDGET_S = 2.0
SECOND_BUDGET_S = 1.0
SECOND_ROWS = 100_000
SECOND_ACCOUNTS = 5_000


def fields(summary) -> tuple[int, int, int, tuple[str, ...]]:
    """Reduce a summary to the four values the export reads."""
    return (summary.count, summary.total_cents, summary.max_cents, tuple(summary.regions))


def expected(rows) -> dict[str, tuple[int, int, int, tuple[str, ...]]]:
    """Roll the ledger up again, independently of the implementation under test.

    Written the obvious way with dictionaries. It is not fast and does not need to be:
    it exists so the correctness assertions do not depend on the code they are checking.
    """
    counts: dict[str, int] = {}
    totals: dict[str, int] = {}
    peaks: dict[str, int] = {}
    regions: dict[str, list[str]] = {}
    for row in rows:
        if row.account in counts:
            counts[row.account] += 1
            totals[row.account] += row.amount_cents
            peaks[row.account] = max(peaks[row.account], row.amount_cents)
            if row.region not in regions[row.account]:
                regions[row.account].append(row.region)
        else:
            counts[row.account] = 1
            totals[row.account] = row.amount_cents
            peaks[row.account] = row.amount_cents
            regions[row.account] = [row.region]
    return {
        account: (counts[account], totals[account], peaks[account], tuple(regions[account]))
        for account in counts
    }


def snapshot(rows) -> list[tuple[str, str, int, str]]:
    """Copy out the values of a ledger so mutation of the caller's rows is detectable."""
    return [(row.account, row.region, row.amount_cents, row.occurred_on) for row in rows]


@functools.lru_cache(maxsize=1)
def full_rollup() -> tuple[list, dict, float]:
    """Load the shipped fixture and time exactly one rollup of it.

    Cached because the unfixed implementation takes about twelve seconds per call, and a
    verification suite that pays that cost six times is a verification suite nobody runs.
    """
    assert FIXTURE.is_file(), (
        f"{FIXTURE.name} is missing. It is generated by tools/make_fixture.py and the "
        "rollup is timed against it"
    )
    rows = load_rows(FIXTURE)
    started = time.perf_counter()
    result = summarise(rows)
    elapsed = time.perf_counter() - started
    return rows, result, elapsed


def second_ledger() -> list[Row]:
    """Build a ledger with a different shape from the one that ships with the task."""
    rng = random.Random(7)
    accounts = [f"cust:{index}" for index in range(SECOND_ACCOUNTS)]
    regions = ("north", "south", "orbit")
    rows: list[Row] = []
    for index in range(SECOND_ROWS):
        account = accounts[rng.randrange(SECOND_ACCOUNTS)]
        amount = -rng.randrange(1, 5000) if rng.random() < 0.1 else rng.randrange(1, 900_000)
        rows.append(Row(account, regions[index % len(regions)], amount, "2026-07-02"))
    return rows


def test_the_shipped_fixture_rolls_up_correctly():
    rows, result, _ = full_rollup()
    assert isinstance(result, dict), "summarise returns a mapping of account to summary"
    reference = expected(rows)
    assert len(result) == len(reference)
    assert set(result) == set(reference)
    for account, values in reference.items():
        assert fields(result[account]) == values, f"{account} rolled up to the wrong figures"
    first_seen = list(dict.fromkeys(row.account for row in rows))
    assert list(result) == first_seen, "the mapping is no longer keyed in first seen order"


def test_the_shipped_fixture_rolls_up_inside_the_budget():
    rows, _, elapsed = full_rollup()
    assert elapsed < BUDGET_S, (
        f"summarise took {elapsed:.3f}s on {len(rows)} rows, and the budget is "
        f"{BUDGET_S:.1f}s. The export cannot wait that long"
    )


def test_a_differently_shaped_ledger_is_also_fast_and_correct():
    rows = second_ledger()
    started = time.perf_counter()
    result = summarise(rows)
    elapsed = time.perf_counter() - started
    assert elapsed < SECOND_BUDGET_S, (
        f"summarise took {elapsed:.3f}s on {len(rows)} rows over {SECOND_ACCOUNTS} accounts "
        f"against a {SECOND_BUDGET_S:.1f}s budget. Whatever made the shipped fixture fast "
        "did not make the rollup fast"
    )
    reference = expected(rows)
    assert len(result) == len(reference)
    for account, values in reference.items():
        assert fields(result[account]) == values


def test_the_answer_is_not_precomputed_for_the_shipped_fixture():
    rows, _, _ = full_rollup()
    slice_of_it = list(rows[:3000])
    baseline = summarise(slice_of_it)
    target = slice_of_it[0]
    edited = list(slice_of_it)
    edited[0] = Row(
        target.account, target.region, target.amount_cents + 10_000_000, target.occurred_on
    )
    moved = summarise(edited)
    assert moved[target.account].total_cents == baseline[target.account].total_cents + 10_000_000, (
        "changing a row did not change the rollup, so the result is coming from somewhere "
        "other than the input"
    )
    assert moved[target.account].max_cents == target.amount_cents + 10_000_000


def test_a_hand_worked_ledger():
    rows = [
        Row("a", "eu-west", 1000, "2026-06-01"),
        Row("b", "us-east", 250, "2026-06-01"),
        Row("a", "us-east", -400, "2026-06-02"),
        Row("a", "eu-west", 7000, "2026-06-02"),
        Row("b", "us-east", 250, "2026-06-03"),
        Row("c", "ap-south", 9, "2026-06-03"),
    ]
    result = summarise(rows)
    assert list(result) == ["a", "b", "c"]
    assert fields(result["a"]) == (3, 7600, 7000, ("eu-west", "us-east"))
    assert fields(result["b"]) == (2, 500, 250, ("us-east",))
    assert fields(result["c"]) == (1, 9, 9, ("ap-south",))
    assert isinstance(result["a"].regions, tuple), "regions is documented as a tuple"


def test_an_empty_ledger_and_a_single_row_ledger():
    assert summarise([]) == {}
    one = summarise([Row("solo", "eu-north", -12, "2026-06-09")])
    assert list(one) == ["solo"]
    assert fields(one["solo"]) == (1, -12, -12, ("eu-north",))


def test_rolling_the_same_ledger_up_twice_gives_the_same_answer():
    rows = [
        Row(f"acct-{index % 17}", ("eu-west", "us-east")[index % 2], index * 3 - 500, "2026-06-04")
        for index in range(400)
    ]
    before = snapshot(rows)
    first = summarise(rows)
    second = summarise(rows)
    assert list(first) == list(second)
    assert {k: fields(v) for k, v in first.items()} == {k: fields(v) for k, v in second.items()}
    assert snapshot(rows) == before, "summarise mutated the rows it was given"
    from_iterator = summarise(iter(rows))
    assert {k: fields(v) for k, v in from_iterator.items()} == {
        k: fields(v) for k, v in first.items()
    }, "summarise no longer accepts an iterator of rows"


def test_first_seen_order_survives_when_it_disagrees_with_sorted_order():
    rows = [
        Row("zulu", "orbit", 5, "2026-06-01"),
        Row("mike", "north", 5, "2026-06-01"),
        Row("alpha", "south", 5, "2026-06-01"),
        Row("mike", "orbit", 5, "2026-06-02"),
        Row("zulu", "north", 5, "2026-06-02"),
    ]
    result = summarise(rows)
    assert list(result) == ["zulu", "mike", "alpha"], (
        "accounts came out in a different order than they first appeared, which breaks the "
        "export downstream"
    )
    assert fields(result["zulu"]) == (2, 10, 5, ("orbit", "north"))
    assert fields(result["mike"]) == (2, 10, 5, ("north", "orbit"))


def test_an_account_of_only_refunds_keeps_its_largest_refund():
    rows = [
        Row("refunds-only", "eu-west", -900, "2026-06-01"),
        Row("refunds-only", "eu-west", -50, "2026-06-02"),
        Row("refunds-only", "us-west", -4000, "2026-06-03"),
    ]
    result = summarise(rows)
    assert fields(result["refunds-only"]) == (3, -4950, -50, ("eu-west", "us-west"))
